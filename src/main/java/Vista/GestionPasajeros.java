    private void cargarTabla(List<Pasajero> listaPasajeros) {
        limpiarCampos();
        modeloTabla.setRowCount(0);

        for (Pasajero p : listaPasajeros) {
            modeloTabla.addRow(new Object[]{
                p.getID_pasajero(),
                p.getDni(),
                p.getApellido(),
                p.getNombre(),
                p.getCorreo(),
                p.getTelefono(),
                p.getEstado()
            });
        }
    }

