    private void cargarTabla() {
        modeloTabla.setRowCount(0);

        List<Pasaje> listaPasaje = pasajeData.listarPasajes();

        for (Pasaje p : listaPasaje) {
            modeloTabla.addRow(new Object[]{
                p.getID_pasaje(),
                p.getID_pasajero(),
                p.getID_lugar(),
                p.getID_ruta(),
                p.getFechaVenta(),
                p.getHoraVenta(),
                p.getPrecio(),
                p.getEstado() == 1 ? "Activo" : "Inactivo"
            });
        }
    }

